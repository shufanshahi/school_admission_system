import { school } from "../content/site";
import type { Hold } from "../api/types";
import { Crest } from "./brand/Crest";
import { IconPrinter } from "./brand/icons";
import { Button } from "./ui/Button";

/** A printable letter of admission. Printing shows only the letter (see styles/print.css). */
export function AdmissionLetter({ hold }: { hold: Hold }) {
  const today = new Date().toLocaleDateString("en-GB", { day: "numeric", month: "long", year: "numeric" });

  return (
    <div className="letter-preview">
      <div className="letter-toolbar">
        <Button onClick={() => window.print()}>
          <IconPrinter size={18} /> Print or save as PDF
        </Button>
      </div>

      <article className="letter" aria-label="Letter of admission">
        <div className="letter-head">
          <Crest size={56} />
          <div>
            <p className="letter-school">{school.name}</p>
            <p className="letter-sub">{school.address.join(", ")}</p>
          </div>
        </div>

        <p className="letter-date">{today}</p>
        <h2>Letter of Admission</h2>

        <p>Dear Parent or Guardian,</p>
        <p>
          We are pleased to confirm that a place has been secured at {school.name} for the student whose birth
          registration number is <strong>{hold.studentId}</strong>, in <strong>{hold.className}</strong>. The admission
          fee has been received.
        </p>
        <p>
          Please keep this letter, together with the reference below, and bring both with you on the day of
          enrolment. The registrar's office will write to you with the dates for orientation and the uniform list.
        </p>

        <dl className="letter-ref">
          <dt>Reference</dt>
          <dd>{hold.holdId}</dd>
          <dt>Class</dt>
          <dd>{hold.className}</dd>
          <dt>Student</dt>
          <dd>{hold.studentId}</dd>
        </dl>

        <p>With our warmest congratulations,</p>
        <p className="letter-sign">{school.registrar}</p>
        <p className="letter-motto">{school.motto}</p>
        <p className="letter-note">Demonstration letter generated by a demo system. It is not a legal document.</p>
      </article>
    </div>
  );
}
